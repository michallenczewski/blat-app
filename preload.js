// Blat — most między oknem a procesem głównym. Wersja przeglądarkowa (do testów) ma ten sam zestaw w renderer/web-api.js.
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  web: false,
  boardsList: () => ipcRenderer.invoke('boards-list'),
  boardLoad: n => ipcRenderer.invoke('board-load', n),
  boardNew: base => ipcRenderer.invoke('board-new', base),
  boardSave: (n, b) => ipcRenderer.invoke('board-save', n, b),
  boardRename: (a, b) => ipcRenderer.invoke('board-rename', a, b),
  boardTrash: n => ipcRenderer.invoke('board-trash', n),
  boardReveal: n => ipcRenderer.invoke('board-reveal', n),
  imagePut: (n, file, bytes) => ipcRenderer.invoke('image-put', n, file, bytes),
  imageCopy: (from, to, file) => ipcRenderer.invoke('image-copy', from, to, file),
  clipWrite: img => ipcRenderer.invoke('clip-write', img),
  clipOurs: () => ipcRenderer.invoke('clip-ours'),
  boardAppend: (n, items) => ipcRenderer.invoke('board-append', n, items),
  imagesPrune: (n, keep) => ipcRenderer.invoke('images-prune', n, keep),
  imageUrl: (n, file) => 'blat://b/' + encodeURIComponent(n) + '/' + encodeURIComponent(file),
  urlFetch: u => ipcRenderer.invoke('url-fetch', u),
  // zamykanie okna: proces główny prosi o zapis ostatnich zmian i czeka na potwierdzenie
  onFlush: cb => ipcRenderer.on('flush', (e, id, reason) => Promise.resolve(reason).then(cb).then(ok => ipcRenderer.send('flushed', id, ok !== false), () => ipcRenderer.send('flushed', id, false))),
  setOnTop: v => ipcRenderer.send('on-top', v),
  setSide: v => ipcRenderer.send('side', v),
  uiState: () => ipcRenderer.invoke('ui-state'),
  chromeColors: (bg, fg, h) => ipcRenderer.send('chrome-colors', bg, fg, h),
  setBare: v => ipcRenderer.send('bare', v),
  // własne przyciski okna (Windows): czy to okno ich używa, sterowanie oknem, stan maksymalizacji
  ownButtons: process.platform === 'win32' ? ipcRenderer.sendSync('own-buttons') : false,
  setOwnButtons: v => ipcRenderer.invoke('own-buttons-set', v),
  winCtl: c => ipcRenderer.send('win-ctl', c),
  onWinMax: cb => ipcRenderer.on('win-max', (e, v) => cb(v)),
  windowButtons: v => ipcRenderer.send('window-buttons', v),
  fullscreenToggle: () => ipcRenderer.send('fullscreen-toggle'),
  onFullscreen: cb => ipcRenderer.on('fullscreen', (e, v) => cb(v)),
  focusWindow: () => ipcRenderer.send('focus-window'),
  updateGet: () => ipcRenderer.invoke('update-get'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdateStatus: cb => ipcRenderer.on('update-status', (e, s) => cb(s)),
});
